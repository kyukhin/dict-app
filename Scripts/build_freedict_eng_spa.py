# Default TEI namespace used by FreeDict.
TEI_NS = "http://www.tei-c.org/ns/1.0"
NS = {"t": TEI_NS}


# Map TEI's abbreviated <pos> values to the long-form labels WordNet uses
# (so search-result POS lines are consistent across sources).
POS_NORMALISATION = {
    "n": "noun",
    "v": "verb",
    "vt": "verb",
    "vi": "verb",
    "adj": "adjective",
    "a": "adjective",
    "adv": "adverb",
    "r": "adverb",
    "prep": "preposition",
    "conj": "conjunction",
    "pron": "pronoun",
    "interj": "interjection",
    "num": "numeral",
    "art": "article",
    "phr": "phrase",
    "pn": "proper noun",
    "propn": "proper noun",
    "abbr": "abbreviation",
}


def _normalise_pos(raw: str) -> str:
    if not raw:
        return ""
    key = raw.strip().lower()
    return POS_NORMALISATION.get(key, key)


def _text(elem) -> str:
    """Concatenated stripped text content of an element, including tails of
    nested children (e.g. <quote> with embedded markup)."""
    if elem is None:
        return ""
    return "".join(elem.itertext()).strip()


def _aggregate_definition(senses_by_pos: dict[str, list[str]]) -> str:
    """Format senses into the same markdown shape WordNet emits:
        **noun**
        1. casa
        2. hogar (informal)
    """
    parts: list[str] = []
    for pos_label, translations in senses_by_pos.items():
        if not translations:
            continue
        if pos_label:
            parts.append(f"**{pos_label}**")
        for i, line in enumerate(translations, 1):
            parts.append(f"{i}. {line}")
        parts.append("")
    return "\n".join(parts).strip()


def parse_tei(tei_path: Path, source: str = SOURCE) -> list[tuple]:
    """Stream the TEI file and produce one row per headword.

    Returned tuples are `(word, definition, phonetic, pos, source)` and
    match the schema of the existing `entries` table.
    """
    rows: list[tuple] = []
    skipped_no_sense = 0

    # iterparse keeps memory bounded — the TEI file can be tens of MB.
    # defusedxml's iterparse hardens against XML entity-expansion attacks.
    safe_et = _safe_etree()
    context = safe_et.iterparse(str(tei_path), events=("end",))
    for event, elem in context:
        tag = elem.tag
        if not tag.endswith("entry"):
            continue

        orths = elem.findall(".//t:form/t:orth", NS)
        if not orths:
            elem.clear()
            continue

        pos_elem = elem.find(".//t:gramGrp/t:pos", NS)
        pos_label = _normalise_pos(_text(pos_elem))

        pron_elem = elem.find(".//t:pron", NS)
        phonetic = _text(pron_elem)

        # Aggregate senses; group by POS so a multi-POS entry renders cleanly.
        senses_by_pos: dict[str, list[str]] = {pos_label: []}
        for sense in elem.findall(".//t:sense", NS):
            translation_chunks: list[str] = []
            # Every <quote> of a translation group, in file order, each once
            # (Issue #108: only the first one used to be kept).
            for cit in sense.findall("t:cit", NS):
                if cit.get("type") != "trans":
                    continue
                for quote in cit.findall("t:quote", NS):
                    qtxt = _text(quote)
                    if qtxt and qtxt not in translation_chunks:
                        translation_chunks.append(qtxt)
            if not translation_chunks:
                continue
            # Append note text in parentheses when present (e.g. "informal").
            note_elem = sense.find("t:note", NS)
            note = _text(note_elem)
            joined = ", ".join(translation_chunks)
            if note:
                joined = f"{joined} ({note})"
            senses_by_pos.setdefault(pos_label, []).append(joined)

        if not senses_by_pos.get(pos_label):
            skipped_no_sense += 1
            elem.clear()
            continue

        definition = _aggregate_definition(senses_by_pos)
        for orth in orths:
            word = _text(orth)
            if not word:
                continue
            rows.append((word, definition, phonetic, pos_label, source))

        elem.clear()

    if skipped_no_sense:
        print(f"  Skipped {skipped_no_sense} entries with no usable translation.")
    return rows


def _render_def(def_elem) -> str:
    """Flatten one `<def>` to display text: each inline `<note>` becomes
    `(note text)` at its position, whitespace is collapsed, and the space a
    line break leaves before a comma is dropped."""
    parts = [def_elem.text or ""]
    for child in def_elem:
        inner = "".join(child.itertext())
        if child.tag == f"{{{TEI_NS}}}note":
            inner = " ".join(inner.split())
            parts.append(f"({inner})" if inner else "")
        else:
            parts.append(inner)
        parts.append(child.tail or "")
    return " ".join("".join(parts).split()).replace(" ,", ",")


def parse_def_tei(tei_path: Path) -> list[tuple[str, str, str]]:
    """Stream a `<sense><def>`-shaped TEI file (e.g. `eng-ell`, where each
    `<def>` is one free-text list of translations) and return raw
    `(spelling, pos, translation_text)` tuples in file order, one per
    `<orth>` and `<def>`. Merging homographs is the caller's job.
    Entry-level `<note>`s (editorial remarks) sit outside `<def>` and are
    dropped."""
    raw: list[tuple[str, str, str]] = []
    safe_et = _safe_etree()
    for _event, elem in safe_et.iterparse(str(tei_path), events=("end",)):
        if elem.tag != f"{{{TEI_NS}}}entry":
            continue
        spellings = [" ".join(_text(orth).split())
                     for orth in elem.findall("t:form/t:orth", NS)]
        pos_label = _normalise_pos(_text(elem.find(".//t:gramGrp/t:pos", NS)))
        texts = [_render_def(d) for d in elem.findall("t:sense/t:def", NS)]
        for spelling in spellings:
            if not spelling:
                continue
            for text in texts:
                if text:
                    raw.append((spelling, pos_label, text))
        elem.clear()
    return raw


# ---------------------------------------------------------------------------
# Public entry points
# ---------------------------------------------------------------------------

def fetch_tei(pair: str = DEFAULT_PAIR,
              cache_dir: Path = inputs.DEFAULT_CACHE_DIR) -> tuple[Path, str]:
    """Fetch, verify and extract the pinned TEI release of `pair`.

    Returns `(tei_path, version)`, where `version` is the release tag (used
    for `dict_metadata.version`)."""
    version = RELEASES[pair]
    tarball = inputs.fetch(f"freedict/freedict-{pair}-{version}.src.tar.xz", cache_dir)
    return _extract_tei(tarball), version


def download_and_parse(pair: str = DEFAULT_PAIR,
                       cache_dir: Path = inputs.DEFAULT_CACHE_DIR) -> tuple[list[tuple], str]:
    """Fetch, verify, extract and parse the pinned TEI of `pair` (a
    `<cit><quote>`-shaped FreeDict release such as eng-spa or ell-eng).

    Returns:
        (rows, version) where `rows` is the list of
        `(word, definition, phonetic, pos, "freedict-<pair>")` tuples
        and `version` is the release tag (used by `build_dictionaries`
        for `dict_metadata.version`).
    """
    tei_path, version = fetch_tei(pair, cache_dir)
    rows = parse_tei(tei_path, source=f"freedict-{pair}")
    return rows, version


# ---------------------------------------------------------------------------
# Stand-alone debug runner
# ---------------------------------------------------------------------------

def _main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dump", type=int, default=0,
                    help="Print the first N parsed entries and exit.")
    ap.add_argument("--pair", default=DEFAULT_PAIR,
                    help="A FreeDict pair with the <cit><quote> TEI shape "
                         "(default: eng-spa).")
    args = ap.parse_args()

    rows, version = download_and_parse(args.pair)
    print(f"\nFreeDict {args.pair} {version}: {len(rows):,} entries parsed.")
    for row in rows[: args.dump]:
        word, definition, phonetic, pos, source = row
        print(f"\n--- {word}  [{pos}]  /{phonetic}/ ---")
        print(definition)
    return 0


if __name__ == "__main__":
    sys.exit(_main())
